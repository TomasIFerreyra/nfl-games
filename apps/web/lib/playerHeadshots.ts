/**
 * Returns the transparent PNG headshot URL for an NFL player, or null if unknown.
 * Checks explicit URL first, then resolves from any provided player name or ID.
 */
export function getPlayerHeadshotUrl(
  name?: string | null,
  playerId?: string | null,
  explicitUrl?: string | null
): string | null {
  if (explicitUrl && explicitUrl.trim().length > 0) {
    return explicitUrl;
  }

  const candidateKeys = [name, playerId].filter(
    (k): k is string => Boolean(k && k.trim().length > 0)
  );

  for (const candidate of candidateKeys) {
    const clean = candidate.toLowerCase().trim();
    const normalized = clean.replace(/[\.\-']/g, " ").replace(/\s+/g, " ");
    const stripped = clean.replace(/[\.\-'\s]/g, "");

    const espnId =
      PLAYER_ESPN_ID_MAP[clean] ||
      PLAYER_ESPN_ID_MAP[normalized] ||
      PLAYER_ESPN_ID_MAP[stripped] ||
      PLAYER_ESPN_ID_MAP[candidate];

    if (espnId) {
      return `${ESPN_HEADSHOT_BASE}/${espnId}.png&w=350&h=254`;
    }
  }

  return null;
}
